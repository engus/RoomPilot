import { expect, test } from '@playwright/test';

test('previews photo-guided furnishings and saves them independently of viewer switches', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('roompilot.language', 'ru'));
  await page.goto('/'); await page.getByRole('button', { name: 'Открыть демо', exact: true }).click();
  await page.getByRole('button', { name: '3D', exact: true }).click();
  const scene = page.getByTestId('scene-3d');
  await expect(scene).toHaveAttribute('data-furnished', 'true');
  const canvas = scene.locator('canvas'); await expect(canvas).toBeVisible();
  await page.getByLabel('Ракурс', { exact: true }).selectOption('demo-living');
  await expect(page.getByLabel('Ракурс', { exact: true })).toHaveValue('demo-living');
  const lit = await canvas.screenshot();
  await page.getByRole('button', { name: 'Свет в предпросмотре', exact: true }).click();
  await expect(scene).toHaveAttribute('data-preview-lights', 'false');
  expect((await canvas.screenshot()).equals(lit)).toBe(false);
  await page.getByRole('button', { name: 'Мебель', exact: true }).click();
  await expect(scene).toHaveAttribute('data-furnished', 'false');
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Экспорт проекта', exact: true }).click();
  const stream = await (await download).createReadStream(), chunks: Buffer[] = [];
  for await (const chunk of stream) chunks.push(Buffer.from(chunk));
  const buffer = Buffer.concat(chunks), saved = JSON.parse(buffer.toString());
  expect(saved.schemaVersion).toBe(5); expect(saved.sceneObjects.length).toBeGreaterThan(35);
  await page.getByLabel('JSON проекта', { exact: true }).setInputFiles({ name: 'home.json', mimeType: 'application/json', buffer });
  await page.getByRole('button', { name: '3D', exact: true }).click();
  await expect(scene).toHaveAttribute('data-furnished', 'true');
  await page.getByTestId('language-select').selectOption('en');
  await expect(page.getByRole('button', { name: 'Preview lights', exact: true })).toBeVisible();
  await page.getByTestId('language-select').selectOption('ru');
  await page.getByRole('button', { name: 'Сбросить масштаб', exact: true }).click();
  await expect(page.getByRole('button', { name: '3D', exact: true })).toBeDisabled();
  const incompleteDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Экспорт проекта', exact: true }).click();
  const incompleteStream = await (await incompleteDownload).createReadStream(), incompleteChunks: Buffer[] = [];
  for await (const chunk of incompleteStream) incompleteChunks.push(Buffer.from(chunk));
  const incomplete = JSON.parse(Buffer.concat(incompleteChunks).toString());
  expect(incomplete.calibration).toBeNull(); expect(incomplete.sceneObjects).toEqual(saved.sceneObjects);
  await page.getByLabel('JSON проекта', { exact: true }).setInputFiles({ name: 'incomplete.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(incomplete)) });
  await expect(page.getByRole('status')).toContainText('Проект импортирован');
});
